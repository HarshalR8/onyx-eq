"""EqState -> PipeWire filter-chain config text, with a slot pool so most edits stay live.

Biquads in series commute, so slot order is irrelevant: a band just needs *some* free slot with
its type's label. Unused slots are set to a neutral (unity) setting. See docs/pipewire-notes.md.
"""
from __future__ import annotations

from collections import Counter
from typing import Sequence

from ..core.models import Band, BandType, EqState

SINK_NAME = "onyx_eq"
OUTPUT_NAME = "onyx_eq.output"
DESCRIPTION = "Onyx EQ"
SMART_NAME = "onyx-eq"

POOL_SIZES = (16, 32, 64, 128, 256, 512)
# spare non-peaking slots added on every (re)build so switching a band's type rarely reloads
SPARES = {
    BandType.LOW_SHELF: 2,
    BandType.HIGH_SHELF: 2,
    BandType.LOW_PASS: 1,
    BandType.HIGH_PASS: 1,
}

Layout = tuple[BandType, ...]


def pool_size(count: int) -> int:
    for size in POOL_SIZES:
        if count <= size:
            return size
    return count


def plan_layout(bands: Sequence[Band]) -> Layout:
    """Slot labels for a fresh chain that fits `bands` with room to grow."""
    need = Counter(b.type for b in bands)
    for t, spare in SPARES.items():
        need[t] = max(need[t], 0) + spare
    need[BandType.PEAKING] = pool_size(need[BandType.PEAKING])
    order = list(BandType)
    return tuple(t for t in order for _ in range(need[t]))


def assign_slots(bands: Sequence[Band], layout: Layout) -> list[int] | None:
    """Slot index per band, or None if the layout can't hold these bands (reload needed)."""
    free: dict[BandType, list[int]] = {}
    for i, t in enumerate(layout):
        free.setdefault(t, []).append(i)
    for v in free.values():
        v.reverse()
    out = []
    for b in bands:
        slots = free.get(b.type)
        if not slots:
            return None
        out.append(slots.pop())
    return out


def neutral(t: BandType) -> tuple[float, float, float]:
    """(Freq, Q, Gain) that makes a slot of this type pass audio unchanged."""
    if t in (BandType.PEAKING, BandType.LOW_SHELF, BandType.HIGH_SHELF):
        return 1000.0, 0.7071, 0.0
    if t is BandType.LOW_PASS:
        return 1_000_000.0, 0.7071, 0.0
    if t is BandType.BAND_PASS:
        return 1000.0, 0.0, 0.0
    return 0.0, 0.7071, 0.0  # highpass, notch, allpass


def slot_name(i: int) -> str:
    return f"band_{i}"


def db_to_mult(db: float) -> float:
    return 10.0 ** (db / 20.0)


def params_for(state: EqState, layout: Layout, assignment: Sequence[int], bypass: bool = False) -> dict[str, float]:
    """Every control value for the chain. Diff against what was last sent to keep updates small."""
    values: dict[int, tuple[float, float, float]] = {i: neutral(t) for i, t in enumerate(layout)}
    if not bypass:
        for band, slot in zip(state.bands, assignment):
            if band.enabled:
                values[slot] = (band.freq, band.q, band.gain if band.type.has_gain else 0.0)
    out: dict[str, float] = {"preamp:Mult": 1.0 if bypass else db_to_mult(state.preamp)}
    for i, (f, q, g) in values.items():
        n = slot_name(i)
        out[f"{n}:Freq"] = float(f)
        out[f"{n}:Q"] = float(q)
        out[f"{n}:Gain"] = float(g)
    return out


def _f(v: float) -> str:
    return repr(float(v))


def build_config(
    layout: Layout,
    params: dict[str, float],
    target: str | None = None,
    channels: Sequence[str] = ("FL", "FR"),
) -> str:
    """A self-contained `pipewire -c` config for the chain."""
    nodes = [
        f'                    {{ type = builtin name = preamp label = linear '
        f'control = {{ "Mult" = {_f(params.get("preamp:Mult", 1.0))} "Add" = 0.0 }} }}'
    ]
    for i, t in enumerate(layout):
        n = slot_name(i)
        f, q, g = (params.get(f"{n}:{k}", d) for k, d in zip(("Freq", "Q", "Gain"), neutral(t)))
        nodes.append(
            f'                    {{ type = builtin name = {n} label = {t.pw_label} '
            f'control = {{ "Freq" = {_f(f)} "Q" = {_f(q)} "Gain" = {_f(g)} }} }}'
        )
    chain = ["preamp"] + [slot_name(i) for i in range(len(layout))]
    links = [
        f'                    {{ output = "{a}:Out" input = "{b}:In" }}' for a, b in zip(chain, chain[1:])
    ]
    # A WirePlumber smart filter: streams headed for `target` are routed through the EQ, while the
    # device itself stays the default, so its volume slider keeps controlling the real hardware.
    smart = '\n                filter.smart = true\n                filter.smart.name = "' + SMART_NAME + '"'
    if target:
        smart += f'\n                filter.smart.target = {{ node.name = "{target}" }}'
    pos = " ".join(channels)
    return f"""# Generated by Onyx EQ. Do not edit; it is rewritten on every reload.
context.properties = {{
    log.level = 0
}}
context.spa-libs = {{
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}}
context.modules = [
    {{ name = libpipewire-module-rt args = {{ }} flags = [ ifexists nofail ] }}
    {{ name = libpipewire-module-protocol-native }}
    {{ name = libpipewire-module-client-node }}
    {{ name = libpipewire-module-adapter }}
    {{ name = libpipewire-module-filter-chain
        args = {{
            node.description = "{DESCRIPTION}"
            media.name       = "{DESCRIPTION}"
            filter.graph = {{
                nodes = [
{chr(10).join(nodes)}
                ]
                links = [
{chr(10).join(links)}
                ]
            }}
            audio.channels = {len(channels)}
            audio.position = [ {pos} ]
            capture.props = {{
                node.name   = "{SINK_NAME}"
                media.class = Audio/Sink
                device.icon-name = "audio-card"{smart}
            }}
            playback.props = {{
                node.name    = "{OUTPUT_NAME}"
                node.passive = true
            }}
        }}
    }}
]
"""
